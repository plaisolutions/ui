import type { UIMessage } from "@plaisolutions/client"
import { cleanup, fireEvent, render, screen } from "@testing-library/react"
import { afterEach, describe, expect, it } from "vitest"
import { ConversationFilesSheet, getConversationFiles } from "../components"

const messages: UIMessage[] = [
  {
    id: "m1",
    role: "user",
    parts: [
      { type: "text", text: "Summarize these" },
      {
        type: "input_file",
        fileUrl: "https://storage.googleapis.com/b/converted.pdf",
        mimeType: "application/pdf",
        metadata: {
          mediaFileId: "mf_up_1",
          wasConverted: true,
          sourceUrl: "https://storage.googleapis.com/b/original.docx",
          originalFileName: "contract.docx",
        },
      },
      {
        type: "input_image",
        url: "https://storage.googleapis.com/b/photo.png",
        metadata: { mediaFileId: "mf_up_2" },
      },
    ],
  },
  {
    id: "m2",
    role: "assistant",
    parts: [
      {
        type: "tool-call",
        id: "t1",
        name: "office_documents",
        toolType: "office_documents",
        input: {},
        state: "completed",
        metadata: {
          type: "office_documents",
          media_files: [
            {
              id: "mf_gen_1",
              name: "summary.xlsx",
              url: "https://storage.googleapis.com/b/summary.xlsx",
            },
            { id: "mf_gen_no_url", name: "pending.docx" },
          ],
        },
      },
    ],
  },
  {
    id: "m3",
    role: "assistant",
    parts: [
      {
        type: "tool-call",
        id: "t2",
        name: "office_documents",
        toolType: "office_documents",
        input: {},
        state: "completed",
        metadata: {
          type: "office_documents",
          media_files: [
            {
              id: "mf_gen_1_again",
              name: "summary.xlsx",
              url: "https://storage.googleapis.com/b/summary.xlsx?X-Goog-Signature=abc",
            },
          ],
        },
      },
    ],
  },
]

describe("getConversationFiles", () => {
  it("collects uploads and generated files once, in conversation order", () => {
    const { uploaded, generated } = getConversationFiles(messages)

    expect(uploaded.map((file) => [file.id, file.name, file.url])).toEqual([
      [
        "mf_up_1",
        "contract.docx",
        "https://storage.googleapis.com/b/original.docx",
      ],
      ["mf_up_2", "photo.png", "https://storage.googleapis.com/b/photo.png"],
    ])
    expect(
      generated.map((file) => [file.id, file.extension, file.messageId]),
    ).toEqual([["mf_gen_1", "xlsx", "m2"]])
  })
})

describe("getConversationFiles with code_execution", () => {
  const codeExecutionMessage = (id: string, files: unknown[]): UIMessage =>
    ({
      id,
      role: "assistant",
      parts: [
        {
          type: "tool-call",
          id: `tool_${id}`,
          name: "analyze_sales",
          toolType: "code_execution",
          input: {},
          state: "completed",
          metadata: {
            type: "code_execution",
            status: "success",
            media_files: files,
          },
        },
      ],
    }) as UIMessage

  it("lists the files generated by code_execution next to office documents", () => {
    const { uploaded, generated } = getConversationFiles([
      ...messages,
      codeExecutionMessage("m4", [
        {
          id: "mf_chart",
          name: "chart.png",
          content_type: "image/png",
          url: "https://storage.googleapis.com/b/chart.png",
        },
        { id: "mf_no_url", name: "pending.csv" },
      ]),
    ])

    expect(uploaded).toHaveLength(2)
    expect(
      generated.map((file) => [
        file.id,
        file.name,
        file.extension,
        file.messageId,
      ]),
    ).toEqual([
      ["mf_gen_1", "summary.xlsx", "xlsx", "m2"],
      ["mf_chart", "chart.png", "png", "m4"],
    ])
  })

  it("lists a file seen twice once, even when its URL was signed again", () => {
    const { generated } = getConversationFiles([
      codeExecutionMessage("a", [
        { id: "mf_1", name: "out.csv", url: "https://s.example/out.csv" },
      ]),
      codeExecutionMessage("b", [
        {
          id: "mf_1",
          name: "out.csv",
          url: "https://s.example/out.csv?X-Goog-Signature=abc",
        },
      ]),
    ])

    expect(generated).toHaveLength(1)
    expect(generated[0]?.messageId).toBe("a")
  })

  it("ignores a code_execution result without files", () => {
    const { generated } = getConversationFiles([
      {
        id: "m",
        role: "assistant",
        parts: [
          {
            type: "tool-call",
            id: "t",
            name: "analyze_sales",
            toolType: "code_execution",
            input: {},
            state: "completed",
            metadata: { type: "code_execution", status: "success" },
          },
        ],
      },
    ])

    expect(generated).toEqual([])
  })
})

describe("ConversationFilesSheet", () => {
  afterEach(cleanup)

  it("opens a localized sheet with uploaded and generated sections", () => {
    render(<ConversationFilesSheet messages={messages} locale="es" />)

    fireEvent.click(
      screen.getByRole("button", { name: "Archivos de la conversación: 3" }),
    )

    expect(
      screen.getByRole("region", { name: "Archivos subidos" }),
    ).toBeTruthy()
    expect(
      screen.getByRole("region", { name: "Archivos generados" }),
    ).toBeTruthy()
    expect(
      screen.getByRole("button", { name: "Descargar: summary.xlsx" }),
    ).toBeTruthy()
  })

  it("says so when the conversation has no files", () => {
    render(
      <ConversationFilesSheet
        messages={[
          { id: "m", role: "user", parts: [{ type: "text", text: "hi" }] },
        ]}
        locale="en"
        open
      />,
    )

    expect(screen.getByText("No files in this conversation yet.")).toBeTruthy()
  })
})
