export function getPersonalConnectorCopy(
  locale?: string | null,
): PersonalConnectorCopy {
  return { ...ENGLISH, ...COPY[getSupportedToolLocale(locale)] }
}

export function fillCopy(
  template: string,
  values: Record<string, string | number>,
): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  )
}
